/**
 * AI buttons and AI videos / images.
 *
 * Runs at document_start after byeai-flag.js. Everything happens locally:
 * we look for the labels platforms already put on AI content ("AI info",
 * "AI-generated", "Altered or synthetic content"...) and cover the post or
 * video they belong to. Posts with clear AI hashtags (#aiart, #midjourney)
 * are covered too.
 *
 * Covering is done with a data attribute + CSS (blur and a ::after notice),
 * so we never insert nodes into React/Lit trees. A click on the cover
 * reveals that one item.
 */
(function () {
  'use strict';

  const byeai = globalThis.byeai;
  if (!byeai) return;

  const host = byeai.host;
  const msg = (key, fallback, args) => {
    try {
      return chrome.i18n.getMessage(key, args || []) || fallback;
    } catch (_) {
      return fallback;
    }
  };

  // ---------------------------------------------------------------- sites

  const SITES = [
    { id: 'youtube', match: /(^|\.)youtube\.com$/ },
    { id: 'tiktok', match: /(^|\.)tiktok\.com$/ },
    { id: 'instagram', match: /(^|\.)instagram\.com$/ },
    { id: 'facebook', match: /(^|\.)facebook\.com$/ },
    { id: 'threads', match: /(^|\.)threads\.(net|com)$/ },
    { id: 'x', match: /(^|\.)(x|twitter)\.com$/ },
    { id: 'pinterest', match: /(^|\.)pinterest\.[a-z.]+$/ },
    { id: 'reddit', match: /(^|\.)reddit\.com$/ },
    { id: 'linkedin', match: /(^|\.)linkedin\.com$/ },
  ];
  const site = (SITES.find((s) => s.match.test(host)) || { id: 'other' }).id;

  // A "card" is the post, tile or video we cover when it carries an AI label.
  const CARDS = {
    youtube: [
      'ytd-rich-item-renderer',
      'ytd-video-renderer',
      'ytd-compact-video-renderer',
      'ytd-grid-video-renderer',
      'ytd-reel-item-renderer',
      'ytd-reel-video-renderer',
      'ytm-shorts-lockup-view-model',
      'yt-lockup-view-model',
    ],
    tiktok: [
      '[data-e2e="recommend-list-item-container"]',
      '[data-e2e="user-post-item"]',
      '[data-e2e="search_top-item"]',
      '[data-e2e="search-card-item"]',
      'article',
    ],
    instagram: ['article'],
    facebook: ['[aria-posinset]', '[role="article"]'],
    threads: ['[data-pressable-container="true"]'],
    x: ['article[data-testid="tweet"]'],
    pinterest: ['[data-test-id="pin"]', '[data-grid-item="true"]', '[data-test-id="closeup-body"]'],
    reddit: ['shreddit-post', 'article'],
    linkedin: ['.feed-shared-update-v2', '[data-urn^="urn:li:activity"]'],
    other: [],
  };
  const cardSelector = CARDS[site].join(',');

  // ------------------------------------------------------------- patterns

  // Labels platforms show on AI content. Matched against the whole text of a
  // short element, so "AI info" matches but a sentence mentioning it does not.
  const LABELS = [
    'ai info',
    'made with ai',
    'ai-generated',
    'ai generated',
    'generated with ai',
    'generated by ai',
    'creator labeled as ai-generated',
    'labeled as ai-generated',
    'altered or synthetic content',
    'ai modified',
    'ai-modified',
    'imagined with ai',
    'contains ai-generated media',
    // fi
    'tekoälytiedot',
    'tekoälyllä luotu',
    'tekoälyn luoma',
    'tekoälyn tuottama',
    'muokattua tai synteettistä sisältöä',
    // de / sv / es / fr
    'ki-info',
    'ki-generiert',
    'ai-genererat',
    'info de ia',
    'generado por ia',
    'infos sur l’ia',
    'généré par ia',
  ];
  const LABEL_SET = new Set(LABELS);
  const normalize = (s) => s.replace(/\s+/g, ' ').trim().toLowerCase();
  // Menus and tag clouds on generic sites, not labels on a piece of content.
  const LABEL_SKIP = 'nav, header, footer, [role="navigation"], [role="menu"], select, option, label';
  // Filter chips and tabs ("AI-generated" as a search filter) are not labels.
  const CHIP_SKIP = 'yt-chip-cloud-chip-renderer, chip-shape, [role="tab"], [role="option"]';
  const isLabel = (s) => s.length <= 60 && LABEL_SET.has(normalize(s));

  // Hashtags that almost always mean AI-made media. Broad ones like #ai or
  // phrases like "made with AI" are left out: they hit news about AI too.
  const AI_TAGS =
    /(?:^|[^\p{L}\p{N}_])(#(?:aiart\w*|aiartwork|aigenerated|aiimages?|aivideos?|aiphotography|aigirls?|midjourney\w*|stablediffusion|dalle\d*|soraai|sora2|openaisora|veo3|klingai|runwayml|leonardoai|sunoai|aigc|tekoälytaide))(?![\p{L}\p{N}_])/iu;
  const findTag = (text) => {
    const m = AI_TAGS.exec(text);
    return m ? m[1] : '';
  };

  // AI entry points inside apps. Exact selectors where we know them...
  const BUTTON_SELECTORS = [
    // X
    'a[href="/i/grok"]',
    'a[href^="/i/grok?"]',
    '[data-testid="GrokDrawer"]',
    '[data-testid="grokImgGen"]',
    'button[aria-label="Grok actions"]',
    // Amazon
    '#nav-rufus-disco',
    '[data-csa-c-content-id*="rufus" i]',
    // Google apps
    '[aria-label="Ask Gemini"]',
    '[aria-label="Show Gemini"]',
    '[aria-label^="Help me write"]',
    '[aria-label^="Help me create"]',
    // LinkedIn
    'button[aria-label*="Rewrite with AI"]',
    'button[aria-label*="Write with AI"]',
    // Microsoft
    'button[aria-label="Copilot"]',
    // Meta
    'a[href*="meta.ai"]',
    'a[aria-label="Meta AI"]',
    // Reddit
    'a[href^="/answers"]',
  ];
  const isGoogle = /(^|\.)google\.[a-z.]+$/.test(host);
  const isAmazon = /(^|\.)amazon\.[a-z.]+$/.test(host);
  if (site === 'youtube') BUTTON_SELECTORS.push('ytd-watch-metadata button[aria-label="Ask"]');
  if (isGoogle) BUTTON_SELECTORS.push('[aria-label="Gemini"]');

  // ...plus exact text / aria-label matches on buttons and links.
  const BUTTON_NAMES = new Set([
    'grok',
    'ask grok',
    'grok actions',
    'meta ai',
    'ask meta ai',
    'ask gemini',
    'copilot',
    'ask copilot',
    'ask rufus',
    'ask ai',
    'ai assistant',
    'ai mode',
    'help me write',
    'rewrite with ai',
    'write with ai',
    'summarize with ai',
    'summarise with ai',
    'summarize this email',
    'reddit answers',
    // fi
    'kysy tekoälyltä',
    'tekoälytila',
    'tekoälyavustaja',
  ]);
  // Plain names that mean something else on other sites (horoscopes, pets).
  if (isGoogle) BUTTON_NAMES.add('gemini');
  if (isAmazon) BUTTON_NAMES.add('rufus');
  const BUTTON_SKIP = '[contenteditable="true"], [data-testid="tweetText"], textarea, input';

  // --------------------------------------------------------------- styles

  const COVER_CSS = `
html[data-byeai-labeled="1"] [data-byeai-cover="labeled"],
html[data-byeai-labeled="1"] [data-byeai-cover="tagged"] {
  isolation: isolate !important;
  overflow: hidden !important;
  cursor: pointer !important;
}
html[data-byeai-labeled="1"] [data-byeai-cover="labeled"] > *,
html[data-byeai-labeled="1"] [data-byeai-cover="tagged"] > * {
  filter: blur(26px) saturate(0.4) !important;
  pointer-events: none !important;
  user-select: none !important;
}
html[data-byeai-labeled="1"] [data-byeai-cover="labeled"]::after,
html[data-byeai-labeled="1"] [data-byeai-cover="tagged"]::after {
  content: attr(data-byeai-note) !important;
  position: absolute !important;
  inset: 0 !important;
  z-index: 2147483000 !important;
  display: flex !important;
  align-items: center !important;
  justify-content: center !important;
  padding: 12px !important;
  background: rgba(15, 23, 42, 0.55) !important;
  color: #fff !important;
  font: 600 13px/1.4 "Segoe UI", system-ui, -apple-system, sans-serif !important;
  text-align: center !important;
  white-space: pre-line !important;
  border-radius: inherit !important;
}`;

  function buttonCss() {
    return (
      BUTTON_SELECTORS.map((s) => `html[data-byeai-buttons="1"] ${s}`).join(',\n') +
      ' { display: none !important; }'
    );
  }

  function injectStyles() {
    const style = document.createElement('style');
    style.id = 'byeai-content-style';
    style.textContent = `${buttonCss()}\n${COVER_CSS}`;
    (document.head || document.documentElement).appendChild(style);
  }

  // --------------------------------------------------------------- buttons

  const hideProps = ['display', 'visibility', 'pointer-events'];

  function hideButton(el, key) {
    if (el.dataset.byeaiHidden) return;
    el.dataset.byeaiHidden = 'buttons';
    el.style.setProperty('display', 'none', 'important');
    // One count per kind of button, not one per tweet.
    byeai.report('buttons', key);
  }

  function scanButtons(root) {
    BUTTON_SELECTORS.forEach((selector) => {
      try {
        root.querySelectorAll(selector).forEach((el) => hideButton(el, selector));
      } catch (_) {
        // selector unsupported in this Chrome version
      }
    });

    root.querySelectorAll('button, [role="button"], a[aria-label], a[role="link"]').forEach((el) => {
      if (el.dataset.byeaiHidden || el.closest(BUTTON_SKIP)) return;
      const label = el.getAttribute('aria-label') || el.textContent || '';
      if (label.length > 40) return;
      if (BUTTON_NAMES.has(normalize(label))) hideButton(el, `name:${normalize(label)}`);
    });
  }

  function unhideButtons() {
    document.querySelectorAll('[data-byeai-hidden="buttons"]').forEach((el) => {
      hideProps.forEach((p) => el.style.removeProperty(p));
      delete el.dataset.byeaiHidden;
    });
  }

  // ---------------------------------------------------------------- covers

  /** @type {WeakMap<Element, { kind: string, source: Node | null }>} */
  const covers = new WeakMap();
  /** @type {WeakMap<Element, string>} */
  const revealed = new WeakMap();
  const coveredList = new Set();
  const ids = new WeakMap();
  let idSeq = 0;

  function nextId(el) {
    if (!ids.has(el)) ids.set(el, ++idSeq);
    return ids.get(el);
  }

  function signature(kind, source) {
    return `${kind}:${source ? normalize(source.textContent || '').slice(0, 80) : ''}`;
  }

  function cover(card, kind, source, tag = '') {
    if (!card || card === document.body || card === document.documentElement) return;
    if (revealed.get(card) === signature(kind, source)) return;
    const current = covers.get(card);
    if (current && (current.kind === 'labeled' || current.kind === kind)) return;

    covers.set(card, { kind, source });
    coveredList.add(card);
    card.dataset.byeaiCover = kind;
    // Say why it is covered, so a wrong call at least explains itself.
    card.dataset.byeaiNote =
      kind === 'labeled'
        ? msg('coverLabeled', 'Labeled as AI by the site\nClick to show')
        : msg('coverTagged', `Tagged ${tag}\nClick to show`, [tag]);
    if (getComputedStyle(card).position === 'static') {
      card.style.setProperty('position', 'relative');
      card.dataset.byeaiPos = '1';
    }
    pauseMedia(card);
    byeai.report('labeled', `cover:${nextId(card)}`);
  }

  function uncover(card) {
    coveredList.delete(card);
    covers.delete(card);
    delete card.dataset.byeaiCover;
    delete card.dataset.byeaiNote;
    if (card.dataset.byeaiPos) {
      card.style.removeProperty('position');
      delete card.dataset.byeaiPos;
    }
  }

  function pauseMedia(card) {
    card.querySelectorAll('video, audio').forEach((m) => {
      try {
        m.pause();
      } catch (_) {
        // ignore
      }
    });
  }

  // Generic fallback when we have no card selector for the site: walk up
  // until we reach something that holds media and looks like a post.
  function genericCard(node) {
    let el = node.nodeType === 1 ? node : node.parentElement;
    for (let i = 0; el && i < 14; i += 1, el = el.parentElement) {
      if (el === document.body) return null;
      const media = el.querySelectorAll('img, video, picture, canvas').length;
      if (!media) continue;
      if (media > 4) return null;
      const r = el.getBoundingClientRect();
      if (r.width > 1000 || r.height > 1400) return null;
      if (r.width >= 160 && r.height >= 120) return el;
    }
    return null;
  }

  function cardFor(node) {
    const el = node.nodeType === 1 ? node : node.parentElement;
    if (!el) return null;

    if (cardSelector) {
      const card = el.closest(cardSelector);
      if (card) return card;
    }
    // YouTube watch page: the label sits in the description or its side
    // panel ("How this content was made"), so cover the player.
    if (site === 'youtube' && el.closest('ytd-watch-flexy, ytd-watch-grid')) {
      return document.querySelector('#movie_player') || document.querySelector('ytd-player');
    }
    return genericCard(el);
  }

  function* labelSources(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(n) {
        const t = n.nodeValue;
        return t && t.length <= 60 && t.trim().length >= 5 ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
      },
    });
    for (let n = walker.nextNode(); n; n = walker.nextNode()) {
      if (isLabel(n.parentElement?.textContent || n.nodeValue)) yield n.parentElement;
      else if (isLabel(n.nodeValue)) yield n.parentElement;
    }
    for (const el of root.querySelectorAll('[aria-label]')) {
      if (isLabel(el.getAttribute('aria-label'))) yield el;
    }
  }

  function scanLabels(root) {
    for (const source of labelSources(root)) {
      if (!source || source.closest('[data-byeai-cover="labeled"]')) continue;
      if (source.closest(CHIP_SKIP) || (site === 'other' && source.closest(LABEL_SKIP))) continue;
      cover(cardFor(source), 'labeled', source);
    }
  }

  function cardText(card) {
    const title = card.querySelector('#video-title, [title]')?.getAttribute('title') || '';
    return `${title} ${card.textContent || ''}`;
  }

  function scanTags(root) {
    if (!cardSelector) return;
    const cards = root.matches?.(cardSelector) ? [root] : [];
    root.querySelectorAll(cardSelector).forEach((c) => cards.push(c));
    cards.forEach((card) => {
      if (covers.has(card)) return;
      const tag = findTag(cardText(card));
      if (tag) cover(card, 'tagged', null, tag);
    });
  }

  // Cards get recycled by infinite feeds and SPA navigation. Drop covers
  // whose reason is gone, and covers for categories that were switched off.
  function recheckCovers() {
    for (const card of [...coveredList]) {
      const info = covers.get(card);
      if (!info || !card.isConnected) {
        coveredList.delete(card);
        continue;
      }
      const off = !byeai.state.labeled;
      let stale = false;
      if (info.kind === 'labeled') {
        const src = info.source;
        stale = !src || !src.isConnected || !isLabel(src.textContent || src.getAttribute?.('aria-label') || '');
      } else {
        stale = !findTag(cardText(card));
      }
      if (off || stale) uncover(card);
    }
  }

  // --------------------------------------------------------------- events

  document.addEventListener(
    'click',
    (event) => {
      const card = event.target instanceof Element ? event.target.closest('[data-byeai-cover]') : null;
      if (!card) return;
      const info = covers.get(card);
      if (!byeai.state.labeled) return;
      event.preventDefault();
      event.stopImmediatePropagation();
      revealed.set(card, signature(card.dataset.byeaiCover, info?.source || null));
      uncover(card);
    },
    true
  );

  // Covered videos stay paused, even when the site tries to autoplay them.
  document.addEventListener(
    'play',
    (event) => {
      const el = event.target;
      if (!(el instanceof HTMLMediaElement)) return;
      const card = el.closest('[data-byeai-cover]');
      if (card && byeai.state.labeled) el.pause();
    },
    true
  );

  // YouTube reuses the player between videos.
  document.addEventListener('yt-navigate-finish', () => {
    const player = document.querySelector('#movie_player');
    if (player && covers.has(player)) uncover(player);
    schedule(document.body);
  });

  // ----------------------------------------------------------------- loop

  let pending = new Set();
  let timer = null;

  function run(roots) {
    const s = byeai.state;
    recheckCovers();
    if (!s.buttons) unhideButtons();
    for (const root of roots) {
      if (!root.isConnected) continue;
      if (s.buttons) scanButtons(root);
      if (s.labeled) {
        scanLabels(root);
        scanTags(root);
      }
    }
  }

  function flush() {
    timer = null;
    const roots = [...pending];
    pending = new Set();
    // A full rescan beats many tiny ones when a lot changed at once.
    run(roots.length > 40 ? [document.body] : roots);
  }

  function schedule(root) {
    if (!root || root.nodeType !== 1) return;
    pending.add(root);
    if (!timer) timer = setTimeout(flush, 250);
  }

  function start() {
    run([document.body]);
    new MutationObserver((mutations) => {
      const s = byeai.state;
      if (!s.buttons && !s.labeled) return;
      for (const m of mutations) {
        if (m.type === 'characterData') schedule(m.target.parentElement);
        else m.addedNodes.forEach((n) => schedule(n.nodeType === 1 ? n : n.parentElement));
      }
    }).observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  injectStyles();
  byeai.onChange(() => {
    if (document.body) run([document.body]);
  });

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start, { once: true });
  } else {
    start();
  }
})();
